package wager

import (
	"fmt"
	"time"

	"github.com/google/uuid"

	"github.com/GuilhermeFaglioni/backend-challenge-go/internal/domain/money"
)

const maxIdempotencyKeyLength = 255

// Result is the financial outcome of a processed Wager Transaction: the balance the
// wallet was left with and its version.
type Result struct {
	Balance       money.Money
	WalletVersion int64
}

// External holds what identifies an external Operation request. An internal opening
// has none of it: Rehydrate refuses a stored opening that does.
type External struct {
	ProviderID                     string
	ExternalTransactionID          string
	IdempotencyKey                 string
	PayloadHash                    PayloadHash
	RoundID                        string
	GameID                         string
	ReferenceExternalTransactionID string
	ReferenceTransactionID         uuid.UUID // the Reference once resolved; Nil until then
}

// Transaction is a Wager Transaction: an immutable value, moved from state to state
// by methods that return the next one. The zero value is invalid.
type Transaction struct {
	id                uuid.UUID
	kind              Kind
	requestedWalletID uuid.UUID // the wallet id as it arrived
	walletID          uuid.UUID // the wallet; Nil only for a Rejection WALLET_NOT_FOUND
	playerID          uuid.UUID
	amount            money.Money
	status            Status
	failureCode       FailureCode
	result            *Result
	external          External
	correlationID     string
	createdAt         time.Time
	updatedAt         time.Time
	processedAt       *time.Time
}

// --- creation ----------------------------------------------------------------------

// OpeningParams are the inputs of the internal opening of a wallet.
type OpeningParams struct {
	ID            uuid.UUID // stable, generated by the use case
	WalletID      uuid.UUID
	PlayerID      uuid.UUID
	Amount        money.Money // the initial balance: positive (a zero one has no opening at all)
	CorrelationID string
	At            time.Time
}

// NewOpening creates the opening of a wallet, still PENDING.
func NewOpening(p OpeningParams) (Transaction, error) {
	if err := checkOpening(p.ID, p.WalletID, p.PlayerID, p.Amount, p.CorrelationID); err != nil {
		return Transaction{}, err
	}
	if p.At.IsZero() {
		return Transaction{}, ErrInvalidTime
	}
	at := p.At.UTC()
	return Transaction{
		id: p.ID, kind: KindOpening, requestedWalletID: p.WalletID, walletID: p.WalletID, playerID: p.PlayerID,
		amount: p.Amount, status: StatusPending, correlationID: p.CorrelationID, createdAt: at, updatedAt: at,
	}, nil
}

func checkOpening(id, walletID, playerID uuid.UUID, amount money.Money, correlationID string) error {
	switch {
	case id == uuid.Nil || walletID == uuid.Nil || playerID == uuid.Nil:
		return ErrInvalidID
	case !amount.IsPositive():
		return ErrInvalidAmount
	case correlationID == "":
		return ErrInvalidCorrelation
	}
	return nil
}

// NewParams are the inputs of the acceptance of an external Operation request.
type NewParams struct {
	ID             uuid.UUID // generated by the use case
	Request        Request
	IdempotencyKey string // as received: the server never replaces it
	CorrelationID  string
	At             time.Time
}

// New accepts an external Operation request as a Wager Transaction, still PENDING.
// The payload hash is the request's, so HTTP and SQS give the same one.
func New(p NewParams) (Transaction, error) {
	switch {
	case p.ID == uuid.Nil:
		return Transaction{}, ErrInvalidID
	case !p.Request.IsValid():
		return Transaction{}, ErrUninitialized
	case !validIdempotencyKey(p.IdempotencyKey):
		return Transaction{}, ErrInvalidIdempotencyKey
	case p.CorrelationID == "":
		return Transaction{}, ErrInvalidCorrelation
	case p.At.IsZero():
		return Transaction{}, ErrInvalidTime
	}
	r := p.Request
	at := p.At.UTC()
	return Transaction{
		id: p.ID, kind: r.Kind(), requestedWalletID: r.WalletID(), walletID: r.WalletID(), playerID: r.PlayerID(),
		amount: r.Amount(), status: StatusPending, correlationID: p.CorrelationID, createdAt: at, updatedAt: at,
		external: External{
			ProviderID: r.ProviderID(), ExternalTransactionID: r.ExternalTransactionID(), IdempotencyKey: p.IdempotencyKey,
			PayloadHash: r.Hash(), RoundID: r.RoundID(), GameID: r.GameID(), ReferenceExternalTransactionID: r.ReferenceExternalTransactionID(),
		},
	}, nil
}

// validIdempotencyKey: the Idempotency-Key header or data.idempotencyKey as received,
// 1 to 255 printable ASCII characters (no spaces).
func validIdempotencyKey(key string) bool {
	if key == "" || len(key) > maxIdempotencyKeyLength {
		return false
	}
	for i := 0; i < len(key); i++ {
		if key[i] < 0x21 || key[i] > 0x7e {
			return false
		}
	}
	return true
}

// --- transitions -------------------------------------------------------------------

// Process moves the transaction to PROCESSED with its financial result. For an
// opening the wallet was just created, so the result is the initial balance at
// version 1; for any other kind it is the wallet's balance and version afterwards.
func (t Transaction) Process(r Result, at time.Time) (Transaction, error) {
	next, err := t.transition(StatusProcessed, at)
	if err != nil {
		return Transaction{}, err
	}
	if err := t.checkResult(r); err != nil {
		return Transaction{}, err
	}
	next.result = &Result{Balance: r.Balance, WalletVersion: r.WalletVersion}
	return next, nil
}

func (t Transaction) checkResult(r Result) error {
	if !r.Balance.IsValid() || r.Balance.IsNegative() || r.Balance.Currency() != t.amount.Currency() || r.WalletVersion < 1 {
		return fmt.Errorf("%w: a balance in the transaction's currency, never negative, and a version of at least 1", ErrInvalidResult)
	}
	if t.kind == KindOpening && (r.Balance != t.amount || r.WalletVersion != 1) {
		return fmt.Errorf("%w: an opening ends with the initial balance at version 1", ErrInvalidResult)
	}
	return nil
}

// Reject moves an external transaction to REJECTED: a business rule refused it. The
// code must be one of the rejection codes. A Rejection WALLET_NOT_FOUND is the one
// that has no wallet: the id that arrived stays as the requested one.
func (t Transaction) Reject(code FailureCode, at time.Time) (Transaction, error) {
	if t.kind == KindOpening {
		return Transaction{}, fmt.Errorf("%w: an opening is never rejected", ErrInvalidStatus)
	}
	if !code.IsRejection() {
		return Transaction{}, fmt.Errorf("%w: %q is not a rejection code", ErrInvalidFailureCode, code)
	}
	next, err := t.transition(StatusRejected, at)
	if err != nil {
		return Transaction{}, err
	}
	next.failureCode = code
	if code == FailureWalletNotFound {
		next.walletID = uuid.Nil
	}
	return next, nil
}

// AwaitReference moves the transaction to PENDING_REFERENCE: it depends on a
// Reference that has not arrived. Only an operation that names a Reference can wait.
func (t Transaction) AwaitReference(at time.Time) (Transaction, error) {
	if t.external.ReferenceExternalTransactionID == "" {
		return Transaction{}, ErrNoReference
	}
	return t.transition(StatusPendingReference, at)
}

// Fail moves the transaction to FAILED: a permanent defect of the infrastructure.
func (t Transaction) Fail(at time.Time) (Transaction, error) {
	next, err := t.transition(StatusFailed, at)
	if err != nil {
		return Transaction{}, err
	}
	next.failureCode = FailureInternalPermanent
	return next, nil
}

// transition checks the state machine and the time, and returns the copy that is
// in the new status and stamped with the time. Terminal statuses are stamped with
// processedAt too.
func (t Transaction) transition(to Status, at time.Time) (Transaction, error) {
	if !t.IsValid() {
		return Transaction{}, ErrUninitialized
	}
	if !t.status.CanTransitionTo(to) {
		return Transaction{}, fmt.Errorf("%w: %s to %s", ErrInvalidTransition, t.status, to)
	}
	if at.IsZero() || at.Before(t.createdAt) {
		return Transaction{}, ErrInvalidTime
	}
	next := t
	next.status = to
	next.updatedAt = at.UTC()
	if to.IsTerminal() {
		processed := next.updatedAt
		next.processedAt = &processed
	}
	return next, nil
}

// --- rehydration -------------------------------------------------------------------

// State is a stored Wager Transaction, for Rehydrate.
type State struct {
	ID                uuid.UUID
	Kind              Kind
	RequestedWalletID uuid.UUID
	WalletID          uuid.UUID // Nil only for a Rejection WALLET_NOT_FOUND
	PlayerID          uuid.UUID
	Amount            money.Money
	Status            Status
	FailureCode       FailureCode
	Result            *Result
	External          External
	CorrelationID     string
	CreatedAt         time.Time
	UpdatedAt         time.Time
	ProcessedAt       *time.Time
}

// Rehydrate restores a stored transaction. It applies no transition and emits no
// event; it only refuses what the database could never hold, and, for an external
// transaction, a payload hash that is not the hash of the request it holds.
func Rehydrate(s State) (Transaction, error) {
	if !s.Status.IsValid() {
		return Transaction{}, fmt.Errorf("%w: %q", ErrInvalidStatus, s.Status)
	}
	if s.CreatedAt.IsZero() || s.UpdatedAt.IsZero() || s.UpdatedAt.Before(s.CreatedAt) {
		return Transaction{}, ErrInvalidTime
	}
	switch {
	case s.Kind == KindOpening:
		if err := checkStoredOpening(s); err != nil {
			return Transaction{}, err
		}
	case s.Kind.IsExternal():
		if err := checkStoredExternal(s); err != nil {
			return Transaction{}, err
		}
	default:
		return Transaction{}, fmt.Errorf("%w: %q", ErrInvalidKind, s.Kind)
	}
	if err := checkOutcome(s); err != nil {
		return Transaction{}, err
	}

	t := Transaction{
		id: s.ID, kind: s.Kind, requestedWalletID: s.RequestedWalletID, walletID: s.WalletID, playerID: s.PlayerID,
		amount: s.Amount, status: s.Status, failureCode: s.FailureCode, external: s.External, correlationID: s.CorrelationID,
		createdAt: s.CreatedAt.UTC(), updatedAt: s.UpdatedAt.UTC(),
	}
	if s.Result != nil {
		r := *s.Result
		t.result = &r
	}
	if s.ProcessedAt != nil {
		p := s.ProcessedAt.UTC()
		t.processedAt = &p
	}
	return t, nil
}

func checkStoredOpening(s State) error {
	if err := checkOpening(s.ID, s.WalletID, s.PlayerID, s.Amount, s.CorrelationID); err != nil {
		return err
	}
	if s.RequestedWalletID != s.WalletID {
		return fmt.Errorf("%w: an opening is for the wallet it created", ErrInvalidID)
	}
	if s.External != (External{}) {
		return ErrExternalFieldsOnOpening
	}
	return nil
}

func checkStoredExternal(s State) error {
	if s.ID == uuid.Nil {
		return ErrInvalidID
	}
	if s.CorrelationID == "" {
		return ErrInvalidCorrelation
	}
	if !validIdempotencyKey(s.External.IdempotencyKey) {
		return ErrInvalidIdempotencyKey
	}
	// The stored fields must still make a valid request, and the hash we stored must
	// be that request's: anything else is a row that was edited or written by a bug.
	request, err := NewRequest(RequestParams{
		ProviderID: s.External.ProviderID, ExternalTransactionID: s.External.ExternalTransactionID,
		PlayerID: s.PlayerID, WalletID: s.RequestedWalletID, RoundID: s.External.RoundID, GameID: s.External.GameID,
		Kind: s.Kind, Amount: s.Amount, ReferenceExternalTransactionID: s.External.ReferenceExternalTransactionID,
	})
	if err != nil {
		return fmt.Errorf("the stored request is not valid: %w", err)
	}
	if request.Hash() != s.External.PayloadHash {
		return ErrPayloadHashMismatch
	}
	if s.External.ReferenceTransactionID != uuid.Nil && s.External.ReferenceExternalTransactionID == "" {
		return fmt.Errorf("%w: a resolved reference needs the reference it resolves", ErrInvalidID)
	}
	// Only the Rejection WALLET_NOT_FOUND has no wallet, and it always has none.
	hasWallet := s.WalletID != uuid.Nil
	if hasWallet && s.WalletID != s.RequestedWalletID {
		return fmt.Errorf("%w: the wallet is the one that was asked for", ErrInvalidID)
	}
	notFound := s.Status == StatusRejected && s.FailureCode == FailureWalletNotFound
	if hasWallet == notFound {
		return fmt.Errorf("%w: a wallet is missing exactly when the wallet was not found", ErrInvalidID)
	}
	return nil
}

// checkOutcome checks that the result, failure code and processing time are the ones
// the status calls for.
func checkOutcome(s State) error {
	external := s.Kind != KindOpening
	switch s.Status {
	case StatusPending:
		if s.Result != nil || s.FailureCode != "" {
			return fmt.Errorf("%w: a pending transaction has no outcome yet", ErrInvalidResult)
		}
	case StatusPendingReference:
		if !external || s.External.ReferenceExternalTransactionID == "" {
			return fmt.Errorf("%w: only an operation that names a reference waits for it", ErrInvalidStatus)
		}
		if s.Result != nil || s.FailureCode != "" {
			return fmt.Errorf("%w: a transaction waiting for its reference has no outcome yet", ErrInvalidResult)
		}
	case StatusProcessed:
		if s.Result == nil || s.FailureCode != "" {
			return fmt.Errorf("%w: a processed transaction has a result and no failure code", ErrInvalidResult)
		}
		probe := Transaction{kind: s.Kind, amount: s.Amount}
		if err := probe.checkResult(*s.Result); err != nil {
			return err
		}
	case StatusRejected:
		if !external {
			return fmt.Errorf("%w: an opening is never rejected", ErrInvalidStatus)
		}
		if !s.FailureCode.IsRejection() || s.Result != nil {
			return fmt.Errorf("%w: a rejection has a rejection code and moved no money", ErrInvalidResult)
		}
	case StatusFailed:
		if s.Result != nil || s.FailureCode != FailureInternalPermanent {
			return fmt.Errorf("%w: a failed transaction moved no money and says why", ErrInvalidResult)
		}
	}
	if s.Status.IsTerminal() != (s.ProcessedAt != nil) {
		return fmt.Errorf("%w: only a finished transaction has a processing time", ErrInvalidTime)
	}
	return nil
}

// --- accessors ---------------------------------------------------------------------

func (t Transaction) IsValid() bool                { return t.id != uuid.Nil }
func (t Transaction) ID() uuid.UUID                { return t.id }
func (t Transaction) Kind() Kind                   { return t.kind }
func (t Transaction) RequestedWalletID() uuid.UUID { return t.requestedWalletID }
func (t Transaction) WalletID() uuid.UUID          { return t.walletID }
func (t Transaction) PlayerID() uuid.UUID          { return t.playerID }
func (t Transaction) Amount() money.Money          { return t.amount }
func (t Transaction) Status() Status               { return t.status }
func (t Transaction) FailureCode() FailureCode     { return t.failureCode }
func (t Transaction) External() External           { return t.external }
func (t Transaction) CorrelationID() string        { return t.correlationID }
func (t Transaction) CreatedAt() time.Time         { return t.createdAt }
func (t Transaction) UpdatedAt() time.Time         { return t.updatedAt }

// Origin is INTERNAL for the opening of a wallet and EXTERNAL for what a provider sent.
func (t Transaction) Origin() Origin {
	if t.kind == KindOpening {
		return OriginInternal
	}
	return OriginExternal
}

// Result is the financial outcome; false until the transaction is processed.
func (t Transaction) Result() (Result, bool) {
	if t.result == nil {
		return Result{}, false
	}
	return *t.result, true
}

// ProcessedAt is when the transaction reached a terminal status; false before.
func (t Transaction) ProcessedAt() (time.Time, bool) {
	if t.processedAt == nil {
		return time.Time{}, false
	}
	return *t.processedAt, true
}
